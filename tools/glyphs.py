#!/usr/bin/env python3
"""Writes src/glyphs.rs: the staff's glyph outlines from Noto Music, as path segments.

gpui drops fonts with no Latin letters, Noto Music among them, so the clef and the
accidentals are drawn as paths instead. Run from the repo root:

  nix shell --impure --expr 'with import (builtins.getFlake "nixpkgs") {}; \
    python3.withPackages (p: [p.fonttools])' -c python3 tools/glyphs.py
"""

from fontTools.pens.basePen import decomposeQuadraticSegment
from fontTools.pens.recordingPen import RecordingPen
from fontTools.ttLib import TTFont

FONT = "/usr/share/fonts/truetype/noto/NotoMusic-Regular.ttf"
# (const name, code point, anchor y: the height that goes on the note's line or space)
GLYPHS = [
    ("G_CLEF", 0x1D11E, 256.0),  # the G line of Noto Music's own staff (U+1D11A)
    ("F_CLEF", 0x1D122, 644.5),  # midway between its dots: the F line (it sits lower than U+1D11A's)
    ("SHARP", 0x266F, None),  # centred
    ("NATURAL", 0x266E, None),  # centred
    ("FLAT", 0x266D, 112.5),  # the middle of the bowl's hole
]

def n(v):
    """A coordinate as a Rust f32 literal."""
    return f"{float(v):.1f}"


font = TTFont(FONT)
cmap, glyphs = font.getBestCmap(), font.getGlyphSet()
out = [
    "//! Staff glyphs from Noto Music (© Google, SIL Open Font License 1.1), as outlines in",
    "//! font units (y up). gpui drops fonts without Latin letters, so they're drawn as paths.",
    "//! Generated by tools/glyphs.py; don't edit.",
    "",
    "/// A contour segment: move, line, quadratic curve (control, end), close.",
    "pub enum Seg {",
    "    M(f32, f32),",
    "    L(f32, f32),",
    "    Q(f32, f32, f32, f32),",
    "    Z,",
    "}",
    "",
    "pub struct Glyph {",
    "    pub segs: &'static [Seg],",
    "    /// The glyph's left edge, and the height that goes on its line or space.",
    "    pub anchor: (f32, f32),",
    "    pub width: f32,",
    "}",
    "",
    "/// A staff space in font units (the line spacing of Noto Music's U+1D11A).",
    "pub const SPACE: f32 = 244.0;",
]
for name, cp, anchor_y in GLYPHS:
    pen = RecordingPen()
    glyphs[cmap[cp]].draw(pen)
    segs, xs, ys, current = [], [], [], None
    for op, args in pen.value:
        for x, y in args:
            xs.append(x)
            ys.append(y)
        if op == "moveTo":
            current = args[0]
            segs.append(f"M({n(args[0][0])}, {n(args[0][1])})")
        elif op == "lineTo":
            current = args[0]
            segs.append(f"L({n(args[0][0])}, {n(args[0][1])})")
        elif op == "qCurveTo":
            for ctrl, end in decomposeQuadraticSegment(args):
                segs.append(f"Q({n(ctrl[0])}, {n(ctrl[1])}, {n(end[0])}, {n(end[1])})")
            current = args[-1]
        elif op == "closePath":
            segs.append("Z")
        else:
            raise SystemExit(f"unexpected {op}")
    if anchor_y is None:
        anchor_y = (min(ys) + max(ys)) / 2
    out += [
        "",
        f"pub const {name}: Glyph = Glyph {{",
        f"    anchor: ({n(min(xs))}, {n(anchor_y)}),",
        f"    width: {n(max(xs) - min(xs))},",
        "    segs: &[",
    ]
    for i in range(0, len(segs), 4):
        out.append("        " + " ".join(f"Seg::{s}," for s in segs[i : i + 4]))
    out += ["    ],", "};"]

with open("src/glyphs.rs", "w") as f:
    f.write("\n".join(out) + "\n")
print(f"wrote src/glyphs.rs ({len(out)} lines)")
